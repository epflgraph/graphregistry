# Dev-mode schema prefix; dev schemas share the canonical file of their base schema.
DEV_SCHEMA_PREFIX = "_1_DEV_"

# Dynamic staging tables built at runtime and excluded from the schema export,
# so they have no canonical key definition to compare against.
DYNAMIC_TABLE_PREFIX = "IndexBuildup_"

# Schemas whose Index_D_* tables are auto-generated at runtime, so they have
