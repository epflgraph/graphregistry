# graphregistry/scripts/integrity_checks/schemas/scan_keys.py
"""
Compare live MySQL key definitions against the canonical keys defined in the
schema files database/init/schemas/schema_*.sql, and verify that every key
indexes the columns it is supposed to index.

Canonical keys are parsed from the CREATE TABLE statements of the exported
schema files (one file per physical schema, see SCHEMA_CONTROL_FILES). Auto-
generated index tables (GraphSearch and Elasticsearch Index_D_* tables) have
no entry in the schema files; their expected keys are computed in memory with
the same GraphTable machinery that creates the tables at runtime
(graphregistry/common/dbstruct.py) — nothing is created in the database. Live
keys are extracted verbatim from SHOW CREATE TABLE. Both sides are normalised
(backticks removed, USING BTREE stripped, whitespace collapsed) so they can be
compared as plain text.

A key is consistent when its name, its type (PRIMARY, UNIQUE, KEY, FULLTEXT,
SPATIAL, FOREIGN) and the ordered list of indexed columns all match the
canonical definition. Remediation SQL drops and re-adds mismatched or missing
keys and drops extra keys. Dropping and re-adding an index on a large table
can be slow, so review the generated statements before using --execute.
"""
