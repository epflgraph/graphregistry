AUTOGENERATED_INDEX_SCHEMAS = {"graphsearch_test", "elasticsearch_cache"}

# Table-name patterns for auto-generated index tables, mirroring the
# GraphTable naming regexes; _Search and _COPY variants are not supported.
AUTOGENERATED_DOC_PATTERN = re.compile(r"^Index_D_([^_]+)$")
AUTOGENERATED_DOCLINK_PATTERNS = {
    "graphsearch_test"    : re.compile(r"^Index_D_([^_]+)_L_([^_]+)_T_(ORG|SEM)$"),
    "elasticsearch_cache" : re.compile(r"^Index_D_([^_]+)_L_([^_]+)$"),
}

# Index group of each auto-generated index schema (GraphTable naming convention).
AUTOGENERATED_INDEX_GROUPS = {
    "graphsearch_test"    : "graphsearch",
    "elasticsearch_cache" : "elasticsearch",
}

# A key definition: (key type, ordered column specs, trailing options such as USING HASH).
KeyDefinition = tuple[str, tuple[str, ...], str]

# CREATE TABLE header pattern used to locate table names in the canonical schema files.
TABLE_NAME_PATTERN = re.compile(
    r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?(\w+)`?\s*\(",
    flags=re.IGNORECASE,
)

# Public Method: Resolve the canonical schema file for a physical schema name.
def resolve_control_file(schema_name: str) -> Path | None:
    """Dev schemas (_1_DEV_*) share the canonical file of their base schema."""
    base_schema = schema_name.removeprefix(DEV_SCHEMA_PREFIX)
    file_name = SCHEMA_CONTROL_FILES.get(base_schema)
    return SCHEMAS_DIR / file_name if file_name else None

# Public Method: Extract the parenthesised body of a CREATE TABLE statement.
def extract_table_body(create_table_sql: str) -> str | None:
    """Return the text between the outermost parentheses of a CREATE TABLE
    statement, so trailing PARTITION BY clauses and table options are excluded
    from key parsing."""
    start = create_table_sql.find("(")
    if start == -1:
        return None

    # Walk forward to the matching ')' so nested parens and partition clauses are handled correctly.
    depth = 1
    end = start + 1
    while end < len(create_table_sql) and depth > 0:
        if create_table_sql[end] == "(":
            depth += 1
        elif create_table_sql[end] == ")":
            depth -= 1
        end += 1
    if depth != 0:
        return None
    return create_table_sql[start + 1:end - 1]

# Public Method: Split a CREATE TABLE body on commas that are not nested in parentheses.
def split_top_level(body: str) -> list[str]:
    """Return the top-level comma-separated parts of a CREATE TABLE body."""
    parts: list[str] = []
    depth = 0
    part_start = 0
    for i, char in enumerate(body):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(body[part_start:i])
            part_start = i + 1
    if part_start < len(body):
        parts.append(body[part_start:])
    return parts

# Public Method: Normalise a key part and extract its USING clause.
def normalise_key_part(part: str) -> tuple[str, str]:
    """Return (normalised part, using clause) for one body part.

    Backticks are removed and whitespace is collapsed. USING BTREE is dropped
    because it is the InnoDB default and MySQL omits it unless explicitly
    quoted, so keeping it would create false positives; USING HASH is a real
    difference and is preserved.
    """
    text = part.replace("`", " ")
    using = "USING HASH" if re.search(r"\bUSING\s+HASH\b", text, flags=re.IGNORECASE) else ""
    text = re.sub(r"\bUSING\s+(BTREE|HASH)\b", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"\s+", " ", text).strip()
    return text, using

# Public Method: Normalise the ordered column list of a key into comparable specs.
def normalise_key_columns(columns_sql: str) -> tuple[str, ...]:
    """Split the column list on top-level commas and strip whitespace, keeping
    index prefixes such as field_value(255) verbatim."""
    columns: list[str] = []
    depth = 0
    part_start = 0
    for i, char in enumerate(columns_sql):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            columns.append(columns_sql[part_start:i])
            part_start = i + 1
    if part_start < len(columns_sql):
        columns.append(columns_sql[part_start:])

    # Strip backticks and all whitespace so 'field_value (255)' equals 'field_value(255)'.
    return tuple(re.sub(r"\s+", "", col.replace("`", "")) for col in columns)

# Public Method: Parse one normalised key part into name, type, columns and options.
def parse_key_part(part: str, using: str) -> tuple[str, str, tuple[str, ...], str] | None:
    """Return (key_name, key_type, columns, options) or None when the part is
    not a key definition."""
    # PRIMARY KEY has no name of its own; it is reported under the reserved name PRIMARY.
    primary_match = re.match(r"^PRIMARY\s+KEY\s*\((.+)\)$", part, flags=re.IGNORECASE)
    if primary_match:
        return "PRIMARY", "PRIMARY", normalise_key_columns(primary_match.group(1)), using

    # Named keys: [UNIQUE|FULLTEXT|SPATIAL] [KEY|INDEX] <name> (<columns>).
    named_match = re.match(
        r"^(?:(UNIQUE|FULLTEXT|SPATIAL)\s+)?(?:KEY|INDEX)\s+(\S+)\s*\((.+)\)$",
        part,
        flags=re.IGNORECASE,
    )
    if named_match:
        key_type = (named_match.group(1) or "KEY").upper()
        return named_match.group(2), key_type, normalise_key_columns(named_match.group(3)), using

    # Unnamed keys: KEY (<columns>). MySQL auto-names them after their first
    # column, which is deterministic here because every generated unnamed key
    # indexes a distinct first column.
    unnamed_match = re.match(r"^(?:KEY|INDEX)\s*\((.+)\)$", part, flags=re.IGNORECASE)
    if unnamed_match:
        columns = normalise_key_columns(unnamed_match.group(1))
        return (columns[0] if columns else None), "KEY", columns, using

    # Foreign keys reference another table; the reference is kept as trailing options.
    foreign_match = re.match(
        r"^CONSTRAINT\s+(\S+)\s+FOREIGN\s+KEY\s*\((.+)\)\s*REFERENCES\s+(\S+)\s*\((.+)\)$",
        part,
        flags=re.IGNORECASE,
    )
    if foreign_match:
        columns = normalise_key_columns(foreign_match.group(2))
        references = ",".join(normalise_key_columns(foreign_match.group(4)))
        options = f"REFERENCES {foreign_match.group(3)} ({references})"
        return foreign_match.group(1), "FOREIGN", columns, options
    return None

# Public Method: Parse every key definition from the body of a CREATE TABLE statement.
def parse_create_table_keys(table_body: str) -> dict[str, KeyDefinition]:
    """Return {key_name: (key_type, columns, options)} for one table body."""
    keys: dict[str, KeyDefinition] = {}
    for part in split_top_level(table_body):
        normalised, using = normalise_key_part(part)
        if not normalised:
            continue
        parsed = parse_key_part(normalised, using)
        if parsed is not None and parsed[0]:
            keys[parsed[0]] = (parsed[1], parsed[2], parsed[3])
    return keys

# Public Method: Parse all canonical key definitions from one schema file.
def parse_schema_file(content: str) -> dict[str, dict[str, KeyDefinition]]:
    """Return {table_name: {key_name: definition}} for one canonical schema file."""
    tables: dict[str, dict[str, KeyDefinition]] = {}
    for match in TABLE_NAME_PATTERN.finditer(content):
        table_name = match.group(1)
        # Hand the parser the statement starting at CREATE TABLE; the body
        # paren is the first one encountered.
        table_body = extract_table_body(content[match.start():])
        if table_body is None:
            continue
        tables[table_name] = parse_create_table_keys(table_body)
    return tables

# Public Method: Load the canonical key definitions from every schema file.
def load_control() -> dict[str, dict[str, dict[str, KeyDefinition]]]:
    """Return {base_schema_name: {table_name: {key_name: definition}}}."""
    control: dict[str, dict[str, dict[str, KeyDefinition]]] = {}
    for base_schema, file_name in SCHEMA_CONTROL_FILES.items():
        file_path = SCHEMAS_DIR / file_name
        if not file_path.exists():
            raise FileNotFoundError(f"Canonical schema file not found: {file_path}")
        control[base_schema] = parse_schema_file(file_path.read_text(encoding="utf-8"))
    return control

# Public Method: Fetch the raw CREATE TABLE statement from MySQL.
def fetch_create_table(db, engine_name, schema_name, table_name) -> str | None:
    """Return the raw CREATE TABLE statement for a single table."""
    query = f"SHOW CREATE TABLE `{schema_name}`.`{table_name}`"
    rows = list(db.execute_query(engine_name=engine_name, query=query))
    return rows[0][1] if rows else None

# Public Method: Parse the column definitions from a generated CREATE TABLE body.
def parse_generated_columns(table_body: str) -> dict[str, str]:
    """Return {column_name: datatype} for a generated CREATE TABLE body."""
    columns: dict[str, str] = {}
    for part in split_top_level(table_body):
        normalised, _ = normalise_key_part(part)
        # Key parts start with a key keyword; everything else is a column definition.
        if re.match(r"^(PRIMARY|UNIQUE|KEY|INDEX|FULLTEXT|SPATIAL|CONSTRAINT)\b", normalised, flags=re.IGNORECASE):
            continue
        tokens = normalised.split()
        if tokens:
            columns[tokens[0]] = " ".join(tokens[1:])
    return columns

# Public Method: Decide whether a column spec indexes TEXT/BLOB without a prefix length.
def is_unprefixed_text_column(column_spec: str, columns: dict[str, str]) -> bool:
    """MySQL rejects keys on TEXT/BLOB columns without a prefix length with
    ERROR 1170, so such keys can never exist on the live server."""
    prefix_match = re.match(r"^(\w+)(\(\d+\))?$", column_spec)
    if not prefix_match or prefix_match.group(2):
        return False
    datatype_tokens = columns.get(prefix_match.group(1), "").split()
    if not datatype_tokens:
        return False
    return datatype_tokens[0].lower() in {
        "text", "mediumtext", "longtext", "tinytext",
        "blob", "tinyblob", "mediumblob", "longblob",
    }

# Public Method: Extract the naming components of an auto-generated index table.
def parse_autogenerated_table_name(schema_name: str, table_name: str) -> tuple[str, str | None, str | None, str] | None:
    """Return (doc_type, link_type, link_subtype, index_group) for an
    auto-generated index table, or None when the name is not supported."""
    index_group = AUTOGENERATED_INDEX_GROUPS.get(schema_name)
    if index_group is None:
        return None
    doc_match = AUTOGENERATED_DOC_PATTERN.match(table_name)
    if doc_match:
        return doc_match.group(1), None, None, index_group
    doclink_match = AUTOGENERATED_DOCLINK_PATTERNS.get(schema_name)
    if doclink_match:
        doclink = doclink_match.match(table_name)
        if doclink:
            link_subtype = doclink.group(3) if len(doclink.groups()) >= 3 else None
            return doclink.group(1), doclink.group(2), link_subtype, index_group
    return None

# Public Method: Decide whether a table is an auto-generated index table.
def is_autogenerated_index_table(schema_name: str, table_name: str) -> bool:
    """GraphSearch and Elasticsearch Index_D_* tables are auto-generated by
    the GraphTable machinery and have no entry in the canonical schema files."""
    return parse_autogenerated_table_name(schema_name, table_name) is not None

# Public Method: Build the structural keys of an auto-generated index table.
def build_structural_control(doc_type, link_type, link_subtype, index_group) -> dict[str, KeyDefinition]:
    """Derive the structural keys from the naming conventions alone: the
    composite uid, one key per id field, the forced doc-rank-link index of
    GraphSearch doc-link tables, and the primary key. Needs no configuration.
    """
    id_fields = ["doc_type", "doc_id"] if link_type is None else ["doc_type", "doc_id", "link_type", "link_subtype", "link_id"]

    # The composite uid guarantees one row per (doc, [subtype,] link) pair.
    control: dict[str, KeyDefinition] = {"uid": ("UNIQUE", tuple(id_fields), "")}

    # Every id field gets its own key, auto-named after its column.
    for id_field in id_fields:
        control[id_field] = ("KEY", (id_field,), "")

    # GraphSearch doc-link tables carry the forced doc-rank-link index.
    if index_group == "graphsearch" and link_type is not None:
        control["idx_doc_rank_link"] = ("KEY", ("doc_type", "doc_id", "row_rank", "link_type", "link_id", "link_subtype"), "")

    # row_id is always the primary key of an auto-generated index table.
    control["PRIMARY"] = ("PRIMARY", ("row_id",), "")
    return control

# Public Method: Compute the expected keys of an auto-generated index table.
def build_autogenerated_control(db, schema_name, table_name) -> tuple[dict[str, KeyDefinition], list[str], str | None]:
    """Compute the expected keys of an auto-generated index table, in memory,
    with the same GraphTable machinery that creates the tables at runtime.

    Nothing is created in the database. When the current configuration cannot
    produce the field list for the table's (doc_type, link_type) pair, a
    structural fallback control is used instead, which needs no
    configuration.

    Returns (control, impossible_keys, uncovered_reason) where
    uncovered_reason is None when fully covered, impossible_keys are key
    names the generator emits on unprefixed TEXT/BLOB columns; live tables
    can never have them, so they are reported but not remediated.
    """
    naming = parse_autogenerated_table_name(schema_name, table_name)
    if naming is None:
        raise ValueError(f"Unsupported auto-generated table name '{table_name}'")
    doc_type, link_type, link_subtype, index_group = naming

    # The machinery adds the config-driven custom-field keys when the pair is covered.
    try:
        tb = GraphTable(db=db, schema_name=schema_name, table_name=table_name)
        table_body = extract_table_body(tb.create_table_sql)
        if not table_body:
            raise ValueError("empty generated CREATE TABLE")
        control = parse_create_table_keys(table_body)
        columns = parse_generated_columns(table_body)
    except (Exception, SystemExit) as exc:
        # The configuration no longer covers this (doc_type, link_type) pair;
        # fall back to the structural keys, which need no configuration.
        structural = build_structural_control(doc_type, link_type, link_subtype, index_group)
        return structural, [], f"{type(exc).__name__}: {exc}"

    # Collect keys MySQL can never create so they can be reported distinctly.
    impossible_keys = [
        key_name
        for key_name, (key_type, key_columns, _) in control.items()
        if key_type == "KEY"
        and any(is_unprefixed_text_column(col, columns) for col in key_columns)
    ]
    return control, impossible_keys, None

# Public Method: Render a key definition as readable SQL-like text.
def format_key(key_name: str, definition: KeyDefinition) -> str:
    """Render a key definition, e.g. UNIQUE KEY uid (object_type,object_id)."""
    key_type, columns, options = definition
    column_list = ",".join(columns)
    if key_type == "PRIMARY":
        rendered = f"PRIMARY KEY ({column_list})"
    elif key_type == "FOREIGN":
        rendered = f"FOREIGN KEY {key_name} ({column_list})"
    else:
        rendered = f"{key_type} KEY {key_name} ({column_list})"
    return f"{rendered} {options}" if options else rendered

# Public Method: Backtick-quote a column spec, keeping index prefixes unquoted.
def quote_column_spec(spec: str) -> str:
    """Quote 'field_value(255)' as '`field_value`(255)'; leave complex specs verbatim."""
    spec_match = re.match(r"^(\w+)(\(\d+\))?$", spec)
    if not spec_match:
        return spec
    return f"`{spec_match.group(1)}`{spec_match.group(2) or ''}"

# Public Method: Build the DROP clause that removes a live key.
def build_drop_clause(key_name: str, definition: KeyDefinition) -> str:
    """Build the DROP clause for a key present in the live table only."""
    key_type, _, _ = definition
    if key_type == "PRIMARY":
        return "DROP PRIMARY KEY"
    return f"DROP KEY `{key_name}`"

# Public Method: Build the ADD clause that re-creates a canonical key.
def build_add_clause(key_name: str, definition: KeyDefinition) -> str:
    """Build the ADD clause for a canonical key, from the control definition."""
    key_type, columns, options = definition
    column_list = ",".join(quote_column_spec(col) for col in columns)
    if key_type == "PRIMARY":
        clause = f"ADD PRIMARY KEY ({column_list})"
    elif key_type == "FOREIGN":
        clause = f"ADD CONSTRAINT `{key_name}` FOREIGN KEY ({column_list}) {options}"
    elif key_type == "KEY":
        clause = f"ADD KEY `{key_name}` ({column_list})"
    else:
        clause = f"ADD {key_type} KEY `{key_name}` ({column_list})"
    return f"{clause} {options}" if options and key_type != "FOREIGN" else clause

# Public Method: Compare the live keys of one table against its canonical keys.
def compare_keys(
    schema_name: str,
    table_name: str,
    live_keys: dict[str, KeyDefinition],
    canonical_keys: dict[str, KeyDefinition],
) -> tuple[list[dict], list[dict]]:
    """Return (verbose rows, issue dicts) for one table.

    Keys are compared by name; a key is consistent only when its type, its
    ordered column list and its trailing options all match the canonical
    definition. Column order matters because MySQL uses the leftmost prefix.
    """
    verbose_rows: list[dict] = []
    issues: list[dict] = []
    for key_name in sorted(set(live_keys) | set(canonical_keys)):
        live_definition = live_keys.get(key_name)
        canonical_definition = canonical_keys.get(key_name)
        is_match = live_definition == canonical_definition

        # Pick the issue type: missing from live, extra in live, or defined differently.
        if live_definition is None:
            issue = "missing"
        elif canonical_definition is None:
            issue = "extra"
        else:
            issue = "mismatch"

        # Record the rendered comparison so --verbose can show every checked key.
        verbose_rows.append(
            {
                "key"      : key_name,
                "actual"   : format_key(key_name, live_definition) if live_definition else "(not present in live table)",
                "expected" : format_key(key_name, canonical_definition) if canonical_definition else "(not defined in canonical schema)",
                "match"    : is_match,
                "issue"    : None if is_match else issue,
            }
        )

        # Keep the raw definitions so remediation SQL can be rebuilt verbatim.
        if not is_match:
            issues.append(
                {
                    "schema"   : schema_name,
                    "table"    : table_name,
                    "key"      : key_name,
                    "issue"    : issue,
                    "actual"   : live_definition,
                    "expected" : canonical_definition,
                }
            )
    return verbose_rows, issues

# Public Method: Print a colorful per-table comparison of live vs canonical keys.
def print_verbose_report(
    verbose_log: dict[tuple[str, str], list[dict]],
    errors_only: bool = False,
) -> None:
    """Print a per-table, per-key comparison of live vs canonical definitions.

    When errors_only is True, only inconsistent keys are shown.
    """
    if not verbose_log:
        return

    # Iterate over the collection.
    for (schema, table), rows in sorted(verbose_log.items()):
        if errors_only:
            rows = [row for row in rows if not row["match"]]
            if not rows:
                continue

        # Continue with the next step.
        console.print(f"\n📋 [bold]{schema}.{table}[/bold]")
        for row in rows:
            if row["match"]:
                console.print(f"  [green]✅ {row['key']}[/green]")
                console.print(f"     {row['actual']}")
            elif row["issue"] == "extra":
                console.print(f"  [yellow]⚠️  {row['key']}[/yellow] (not defined in canonical schema)")
                console.print(f"     [yellow]{row['actual']}[/yellow]")
            elif row["issue"] == "impossible":
                console.print(f"  [yellow]⚠️  {row['key']}[/yellow] (on unprefixed TEXT/BLOB column; MySQL rejects it)")
                console.print(f"     [yellow]{row['expected']}[/yellow]")
            else:
                console.print(f"  [red]❌ {row['key']}[/red] ({row['issue']})")
                console.print(f"     [red]actual:   {row['actual']}[/red]")
                console.print(f"     [green]expected: {row['expected']}[/green]")

# Public Method: Print a histogram of key issues grouped by issue type and key name.
def print_issue_histogram(issues: list[dict]) -> None:
    """Print how often each issue type occurs for each key name."""
    if not issues:
        return

    # Declare the counts data structure.
    counts: dict[tuple[str, str], int] = defaultdict(int)
    for issue in issues:
        counts[(issue["issue"], issue["key"])] += 1

    # Sort by frequency descending, then by issue/key text for stability.
    sorted_pairs = sorted(counts.items(), key=lambda item: (-item[1], item[0][0], item[0][1]))

    # Continue with the next step.
    console.print("\n📊 [bold]Key issue histogram[/bold] (issue × key)")
    issue_colors = {"missing": "red", "extra": "yellow", "mismatch": "red"}
    for (issue, key_name), count in sorted_pairs:
        color = issue_colors[issue]
        console.print(f"  [red]{count:>3}[/red] × [{color}]{issue:<8}[/{color}] {key_name}")

# Public Method: Build a single ALTER TABLE per table combining DROP and ADD key clauses.
def build_combined_statements(key_issues: list[dict]) -> list[str]:
    """Build one ALTER TABLE per table; DROPs come first so re-added keys do
    not collide with the stale definitions."""
    grouped: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for issue in key_issues:
        grouped[(issue["schema"], issue["table"])].append(issue)

    # Prepare statements for the following steps.
    statements: list[str] = []
    for (schema, table), issues in sorted(grouped.items()):
        clauses: list[str] = []

        # Drop the extra and mismatched keys first.
        for issue in issues:
            if issue["issue"] in {"extra", "mismatch"}:
                clauses.append(build_drop_clause(issue["key"], issue["actual"]))

        # Re-add the missing and mismatched keys from the canonical definitions.
        for issue in issues:
            if issue["issue"] in {"missing", "mismatch"}:
                clauses.append(build_add_clause(issue["key"], issue["expected"]))

        # Skip tables that have no clauses to apply.
        if not clauses:
            continue

        # Compose a single ALTER TABLE statement for this schema.table.
        statements.append(
            f"ALTER TABLE `{schema}`.`{table}`\n"
            + ",\n".join(f"    {clause}" for clause in clauses)
            + ";"
        )
    return statements

# Public Method: Parse arguments and run the key consistency scan.
def main():
    parser = argparse.ArgumentParser(
        description=(
            "Compare live MySQL keys (names, types and indexed columns) against "
            "the canonical keys in database/init/schemas/schema_*.sql, and "
            "generate or execute remediation SQL."
        )
    )
    parser.add_argument(
        "-x",
        "--execute",
        action = "store_true",
        help   = "Execute the generated ALTER TABLE statements. DDL is auto-committed.",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action = "store_true",
        help   = "Print a per-table, per-key comparison of live vs canonical definitions.",
    )
    parser.add_argument(
        "-e",
        "--errors-only",
        action = "store_true",
        help   = "With --verbose, show only keys that do not match the canonical schema.",
    )
    args = parser.parse_args()

    # --errors-only is meaningless without the comparison report, so imply --verbose.
    if args.errors_only:
        args.verbose = True

    # Prepare db for the following steps.
    from graphdb.client import Environments
    from graphdb.domain.models.mdl_config import GraphDBConfig
    from graphregistry.adapters.persistence.mysql.databaseclient import MySQLDatabaseClient
    from graphregistry.common.paths import CONFIG_DB_PATH
    db = MySQLDatabaseClient(Environments(GraphDBConfig.from_file(CONFIG_DB_PATH)))
    engine_name = "coresrv_env"

    # Prepare canonical control for the following steps.
    control = load_control()

    # Accumulate issues and per-table comparison details across schemas.
    key_issues: list[dict] = []
    # Live tables that have no canonical definition (possible schema drift).
    unknown_tables: list[dict] = []
    # Dynamic staging tables skipped because they have no canonical definition.
    skipped_dynamic: list[dict] = []
    # Canonical tables absent from the live schema (informational only).
    absent_canonical: list[dict] = []
    # Keys the generator emits on unprefixed TEXT/BLOB columns; MySQL rejects
    # them with ERROR 1170, so live tables can never have them.
    impossible_key_log: dict[tuple[str, str], list[str]] = {}
    # Index tables the current configuration no longer covers; their expected
    # keys fall back to the structural keys alone.
    uncovered_tables: dict[tuple[str, str], str] = {}
    # verbose_log records every checked key when --verbose is requested.
    verbose_log: dict[tuple[str, str], list[dict]] = defaultdict(list)

    # Scan every configured schema and its tables.
    for schema_name in SCHEMAS:
        base_schema = schema_name.removeprefix(DEV_SCHEMA_PREFIX)
        schema_control = control.get(base_schema)

        # Schemas without a canonical schema file cannot be checked for keys.
        if schema_control is None:
            console.print(f"⚠️  No canonical schema file for '{schema_name}'; skipping.")
            continue

        # Skip tables whose names start with an underscore (internal/temp tables).
        tables = [
            t
            for t in db.get_tables_in_schema(
                engine_name=engine_name, schema_name=schema_name
            )
            if not t.startswith("_")
        ]
        seen_tables = set(tables)

        # Scan every table in the current schema.
        for table_name in tables:

            # Allow the operator to abort a long-running scan via a sentinel file.
            if os.path.exists('abort'):
                print('Script aborted by request.')
                exit()

            # Dynamic staging tables are excluded from the schema export and
            # have no canonical key definition to compare against.
            if table_name.startswith(DYNAMIC_TABLE_PREFIX):
                skipped_dynamic.append({"schema": schema_name, "table": table_name})
                continue

            # Auto-generated index tables are controlled by the GraphTable
            # machinery instead of the canonical schema files.
            is_autogenerated = (
                schema_name in AUTOGENERATED_INDEX_SCHEMAS
                and is_autogenerated_index_table(schema_name, table_name)
            )

            # Resolve the canonical keys before fetching the live definition, so
            # tables whose generation fails are skipped without a DB round trip.
            if is_autogenerated:
                try:
                    canonical_keys, impossible_keys, uncovered_reason = build_autogenerated_control(
                        db, schema_name, table_name
                    )
                except Exception as exc:
                    console.print(f"❌ Could not compute expected keys for '{schema_name}.{table_name}': {exc}")
                    continue
                if uncovered_reason:
                    uncovered_tables[(schema_name, table_name)] = uncovered_reason
                if impossible_keys:
                    impossible_key_log[(schema_name, table_name)] = impossible_keys
            else:
                # Live tables missing from the canonical schema are reported but not remediated.
                canonical_keys = schema_control.get(table_name)
                if canonical_keys is None:
                    unknown_tables.append({"schema": schema_name, "table": table_name})
                    continue

            # Fetch the raw CREATE TABLE statement and parse its keys verbatim.
            create_table_sql = fetch_create_table(
                db, engine_name, schema_name, table_name
            )
            if not create_table_sql:
                continue
            table_body = extract_table_body(create_table_sql)
            live_keys = parse_create_table_keys(table_body) if table_body else {}

            # Compare every live key against the canonical definition.
            rows, issues = compare_keys(
                schema_name, table_name, live_keys, canonical_keys
            )

            # Missing keys on unprefixed TEXT/BLOB columns can never exist on
            # the live server; keep them out of the remediation SQL.
            if is_autogenerated and impossible_keys:
                for row in rows:
                    if row["key"] in impossible_keys and not row["match"]:
                        row["issue"] = "impossible"
                issues = [
                    issue
                    for issue in issues
                    if not (issue["key"] in impossible_keys and issue["issue"] == "missing")
                ]

            # Record the per-table results for the reports and the histogram.
            verbose_log[(schema_name, table_name)].extend(rows)
            key_issues.extend(issues)

        # Canonical tables absent from the live schema are informational only.
        for table_name in sorted(set(schema_control) - seen_tables):
            absent_canonical.append({"schema": schema_name, "table": table_name})

    # --------------------------------------------------
    # Report results.
    # --------------------------------------------------

    # Print the per-table comparison when verbose mode is enabled.
    if args.verbose:
        print_verbose_report(verbose_log, errors_only=args.errors_only)

    # Warn about live tables that the canonical schema does not define.
    if unknown_tables:
        console.print("\n⚠️  [bold]Live tables with no canonical definition:[/bold]")
        for t in unknown_tables:
            console.print(f"  [yellow]{t['schema']}.{t['table']}[/yellow]")

    # Warn about keys the generator emits but MySQL can never create; fixing
    # the generator (the dbstruct.py TEXT subset logic) is the remedy here.
    if impossible_key_log:
        console.print("\n⚠️  [bold]Keys the generator cannot create (unprefixed TEXT/BLOB columns):[/bold]")
        for (schema, table), key_names in sorted(impossible_key_log.items()):
            console.print(f"  [yellow]{schema}.{table}: {', '.join(sorted(key_names))}[/yellow]")

    # Warn about index tables the current configuration no longer covers;
    # only their structural keys are checked, custom-field keys are unknown.
    if uncovered_tables:
        console.print("\n⚠️  [bold]Index tables not fully covered by the current configuration (structural keys only):[/bold]")
        for (schema, table), reason in sorted(uncovered_tables.items()):
            console.print(f"  [yellow]{schema}.{table}[/yellow]")
            if args.verbose:
                console.print(f"     [yellow]{reason}[/yellow]")

    # Print remediation SQL when any key issue was detected.
    if key_issues:
        if args.execute:
            print("-- EXECUTING generated ALTER TABLE statements. DDL is auto-committed.\n")
        else:
            print("-- Review before running. Key definitions are taken from the canonical schema files")
            print("-- in database/init/schemas/. Dropping and re-adding indexes on large tables can be slow.\n")

        # Build and optionally execute remediation ALTER TABLE statements.
        statements = build_combined_statements(key_issues)
        total = len(statements)
        for idx, stmt in enumerate(statements, start=1):
            print(f"-- [{idx}/{total}]")
            print_sql(stmt, title="Remediation")
            if args.execute:
                try:
                    db.execute_query(engine_name=engine_name, query=stmt)
                    print("  -> OK")
                except Exception as exc:
                    print(f"  -> FAILED: {exc}")
            print()
    elif impossible_key_log or uncovered_tables:
        print("All checked keys match their expected definitions; see the warnings above for tables that are only partially covered.")
    else:
        print("All keys match the canonical schema definitions (names, types and indexed columns).")

    # Always print the issue histogram when there are key issues.
    print_issue_histogram(key_issues)

    # Report dynamic tables and absent canonical tables when verbose mode is enabled.
    if args.verbose and skipped_dynamic:
        console.print(f"\n[yellow]Skipped {len(skipped_dynamic)} dynamic staging tables (IndexBuildup_*).[/yellow]")
    if args.verbose and absent_canonical:
        console.print("\n⚠️  [bold]Canonical tables absent from the live schema:[/bold]")
        for t in absent_canonical:
            console.print(f"  [yellow]{t['schema']}.{t['table']}[/yellow]")

# Run the scan when this script is executed directly.
if __name__ == "__main__":
    main()
